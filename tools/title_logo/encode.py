import os, sys, struct
sys.path.insert(0,'.')
from rx2 import textures; from dxt import decode_dxt5, png, swap16
# Canvas = the logo's letters as the movie places them (pressstart.apt sprites 45/50/55/60 at
# x -109/-16/102/196, shapes in pressstart.geo): x = movie x + 141, y = movie y + 41.
W,H=369,85
neon=open('neon.rgba','rb').read()
def to565(c): return ((c[0]*31+127)//255)<<11 | ((c[1]*63+127)//255)<<5 | ((c[2]*31+127)//255)
def from565(v): return (((v>>11)&31)*255//31, ((v>>5)&63)*255//63, (v&31)*255//31)
def enc_block(px):  # px: 16 rgba tuples
    al=[p[3] for p in px]; a0,a1=max(al),min(al)
    if a0==a1: a0=min(255,a0+1) if a0<255 else a0; a1=a1 if a0!=a1 else max(0,a1-1)
    pal=[a0,a1]+[((7-i)*a0+i*a1)//7 for i in range(1,7)]
    ai=[min(range(8),key=lambda k:abs(pal[k]-a)) for a in al]
    abits=0
    for i,k in enumerate(ai): abits|=k<<(3*i)
    # color endpoints: weighted by alpha, bbox along luminance
    vis=[p for p in px if p[3]>8] or px
    lum=lambda p: p[0]*3+p[1]*6+p[2]
    hi=max(vis,key=lum); lo=min(vis,key=lum)
    c0,c1=to565(hi),to565(lo)
    if c0<c1: c0,c1=c1,c0
    if c0==c1:
        cols=[from565(c0)]*4; idx=[0]*16
    else:
        p0,p1=from565(c0),from565(c1)
        cols=[p0,p1,tuple((2*a+b)//3 for a,b in zip(p0,p1)),tuple((a+2*b)//3 for a,b in zip(p0,p1))]
        idx=[min(range(4),key=lambda k:sum((cols[k][j]-p[j])**2 for j in range(3))) for p in px]
    cb=0
    for i,k in enumerate(idx): cb|=k<<(2*i)
    return bytes([a0,a1])+abits.to_bytes(6,'little')+struct.pack('<HHI',c0,c1,cb)
def encode(img,w,h,pitch,template):
    out=bytearray(swap16(template))  # keep padding as in the stock raster
    rowblocks=pitch//4
    for by in range(h//4):
        for bx in range(w//4):
            px=[]
            for i in range(16):
                x=bx*4+i%4; y=by*4+i//4; q=(y*w+x)*4; px.append(tuple(img[q:q+4]))
            o=(by*rowblocks+bx)*16; out[o:o+16]=enc_block(px)
    return swap16(bytes(out))
rx2=open('pressstart.rx2','rb').read(); ts=textures(rx2)
# pieces: (texture index, canvas x, canvas y, w, h, owned columns [x0, x1))
# Neighbours overlap by 3 / 10 / 2 pixels and add up on screen, so each canvas
# column belongs to one piece only.
pieces=[(17,0,5,64,64,0,63),(16,0,69,64,16,0,63),
        (20,61,0,128,64,63,184),(19,61,64,128,16,63,184),
        (23,179,0,128,64,184,306),(22,179,64,128,16,184,306),
        (26,305,2,64,64,306,369),(25,305,66,64,16,306,369)]
def fnv(b):
    h=0xcbf29ce484222325
    for x in b: h=((h^x)*0x100000001b3)&0xFFFFFFFFFFFFFFFF
    return h
rasters=[]; preview=bytearray(W*H*4)
for idx,x0,y0,w,h,own0,own1 in pieces:
    t=ts[idx]; assert (t['w'],t['h'])==(w,h), (idx,t['w'],t['h'])
    stock=rx2[t['raster']:t['raster']+t['size']]
    img=bytearray(w*h*4)
    for y in range(h):
        for x in range(w):
            cx,cy=x0+x,y0+y
            if own0<=cx<own1 and 0<=cy<H:
                q=(cy*W+cx)*4; img[(y*w+x)*4:(y*w+x)*4+4]=neon[q:q+4]
    r=encode(img,w,h,t['pitch'],stock)
    assert len(r)==len(stock)
    rasters.append((idx,w,h,t['pitch'],fnv(stock),r,t['fetch'][2]))
    dec=decode_dxt5(r,w,h,t['pitch'])
    for y in range(h):  # additive, like the game
        for x in range(w):
            cx,cy=x0+x,y0+y
            if 0<=cx<W and 0<=cy<H:
                d=(cy*W+cx)*4; e=(y*w+x)*4
                for k in range(4): preview[d+k]=min(255,preview[d+k]+dec[e+k])
png('encoded_preview.png',W,H,preview)
# C++ header
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'../../dylib/title_logo.h'),'w') as f:
    f.write('// The press-start screen\'s logo letters (bootflow/pressstart.rx2 in fedynamic.big), redrawn\n')
    f.write('// as "skate.live". Generated by tools/title_logo/make.sh: each entry is a stock\n')
    f.write('// DXT5 raster\'s FNV-1a hash and size, and the replacement raster (same layout).\n#pragma once\n#include <cstdint>\n\n')
    f.write('struct TitleLogoPiece {\n  uint64_t stock_hash;\n  uint32_t size;\n  uint32_t fetch_size;  // fetch dword 2: width / height\n  const uint8_t* raster;\n};\n\n')
    for k,(idx,w,h,p,hsh,r,fs) in enumerate(rasters):
        f.write(f'inline constexpr uint8_t kTitleLogo{k}[{len(r)}] = {{')
        f.write(','.join(str(b) for b in r)); f.write('};\n')
    f.write('\ninline constexpr TitleLogoPiece kTitleLogo[] = {\n')
    for k,(idx,w,h,p,hsh,r,fs) in enumerate(rasters):
        f.write(f'    {{0x{hsh:016X}ull, {len(r)}, 0x{fs:X}, kTitleLogo{k}}},  // texture {idx}, {w}x{h}\n')
    f.write('};\n')
print('ok', [(r[0],hex(r[4])) for r in rasters])
